#!/usr/bin/env python3
"""Generate the app-traffic model parameters from contracts/app_traffic/parameters.yaml.

Output (committed; ``--check`` exits 1 when it is out of date, ci/check.sh
runs that): ``core/src/app_traffic/params.rs`` — one constant per parameter,
typed by its distribution, with its unit, status and source as the doc
comment, and ``PARAMS_VERSION`` (a hash of the YAML), which the Logger writes
into header.json through the generated ``Contract.java``
(``java_contract.py`` imports ``params_version`` from here).

    analysis/.venv/bin/python contracts/codegen/app_params.py          # write
    analysis/.venv/bin/python contracts/codegen/app_params.py --check  # CI
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "contracts" / "app_traffic" / "parameters.yaml"
RUST_OUT = ROOT / "core" / "src" / "app_traffic" / "params.rs"

KINDS = ("lognormal", "uniform", "int_range", "probability", "cumulative", "choice", "fixed")
STATUSES = ("unverified", "reported", "verified", "project_choice")
FIXED_TYPES = ("f64", "u64", "u32", "usize")


def params_version() -> str:
    """The parameter set's version: the first 12 hex digits of the YAML's SHA-256."""
    return hashlib.sha256(SOURCE.read_bytes()).hexdigest()[:12]


def load() -> list[dict]:
    doc = yaml.safe_load(SOURCE.read_text())
    defaults = doc.get("defaults", {})
    seen, out = set(), []
    for p in doc["parameters"]:
        p = {**defaults, **p}
        kinds = [k for k in KINDS if k in p]
        assert len(kinds) == 1, f"{p['id']}: exactly one of {KINDS}"
        assert p["id"] not in seen, f"{p['id']}: listed twice"
        assert p["status"] in STATUSES, f"{p['id']}: status {p['status']}"
        assert re.fullmatch(r"[a-z_]+\.[a-z0-9_]+", p["id"]), f"{p['id']}: id is group.name"
        if kinds[0] == "fixed":
            assert p.get("type") in FIXED_TYPES, f"{p['id']}: fixed needs a type in {FIXED_TYPES}"
        seen.add(p["id"])
        out.append({**p, "kind": kinds[0]})
    return out


def f(x) -> str:
    """A Rust f64 literal with the YAML number's exact value."""
    s = repr(float(x))
    return s if ("." in s or "e" in s) else s + ".0"


def rust(params: list[dict]) -> str:
    o = [
        "//! GENERATED by contracts/codegen/app_params.py from",
        "//! contracts/app_traffic/parameters.yaml — do not edit; change the YAML and regenerate.",
        "//! Every number the app-traffic models draw from, with where it comes from.",
        "",
        "/// The parameter set's version (a hash of parameters.yaml), written into",
        "/// header.json so a result names the numbers it ran with.",
        f'pub const PARAMS_VERSION: &str = "{params_version()}";',
        "",
        "/// Log-normal with this median and spread (sigma of ln x), clamped to",
        "/// `min..=max`.",
        "#[derive(Debug, Clone, Copy, PartialEq)]",
        "pub struct LogNormal {",
        "    pub median: f64,",
        "    pub sigma: f64,",
        "    pub min: f64,",
        "    pub max: f64,",
        "}",
        "",
        "/// Uniform in `min..max`.",
        "#[derive(Debug, Clone, Copy, PartialEq)]",
        "pub struct Uniform {",
        "    pub min: f64,",
        "    pub max: f64,",
        "}",
        "",
        "/// A whole number in `min..=max`, each equally likely.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct IntRange {",
        "    pub min: u64,",
        "    pub max: u64,",
        "}",
    ]
    for p in params:
        name = p["id"].replace(".", "_").upper()
        doc = p.get("doc", "").strip()
        o.append("")
        if doc:
            o.append(f"/// {doc}")
            o.append("///")
        o.append(f"/// `{p['id']}` ({p['unit']}) — {p['status']}: {p['source']}.")
        k = p["kind"]
        if k == "lognormal":
            d = p[k]
            o.append(
                f"pub const {name}: LogNormal = LogNormal {{ median: {f(d['median'])}, sigma: {f(d['sigma'])},"
                f" min: {f(d['min'])}, max: {f(d['max'])} }};"
            )
        elif k == "uniform":
            d = p[k]
            o.append(f"pub const {name}: Uniform = Uniform {{ min: {f(d['min'])}, max: {f(d['max'])} }};")
        elif k == "int_range":
            d = p[k]
            o.append(f"pub const {name}: IntRange = IntRange {{ min: {int(d['min'])}, max: {int(d['max'])} }};")
        elif k == "probability":
            o.append(f"pub const {name}: f64 = {f(p[k])};")
        elif k in ("cumulative", "choice"):
            vals = ", ".join(f(x) for x in p[k])
            o.append(f"pub const {name}: [f64; {len(p[k])}] = [{vals}];")
        else:  # fixed
            ty = p["type"]
            val = f(p[k]) if ty == "f64" else str(int(p[k]))
            o.append(f"pub const {name}: {ty} = {val};")
    src = "\n".join(o) + "\n"
    return subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"], input=src, capture_output=True, text=True, check=True
    ).stdout


def main() -> int:
    out = rust(load())
    if "--check" in sys.argv[1:]:
        if not RUST_OUT.exists() or RUST_OUT.read_text() != out:
            print("app-traffic parameters out of date (run contracts/codegen/app_params.py):")
            print("  ", RUST_OUT.relative_to(ROOT))
            return 1
        print("OK: app-traffic parameters match contracts/app_traffic/parameters.yaml.")
        return 0
    if not RUST_OUT.exists() or RUST_OUT.read_text() != out:
        RUST_OUT.write_text(out)
        print("wrote", RUST_OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
