#!/usr/bin/env python3
"""Generate the wire packet codec and its docs from contracts/packets/layouts.yaml.

Outputs (committed; ``--check`` exits 1 when any is out of date, ci/check.sh
runs that):

- ``core/src/packet/layouts.rs``: the Rust codec both nodes use — the pkt_t
  and ver constants, one struct per layout with ``to_bytes`` / ``decode`` and
  its sizes, and a golden test per layout against its vector file;
- the layout table of each layout in its spec (``contracts/packets/*.md``)
  and the type registry in ``contracts/packets/README.md``, between
  ``<!-- BEGIN GENERATED: ... -->`` / ``<!-- END GENERATED: ... -->``.

    analysis/.venv/bin/python contracts/codegen/packet_codec.py          # write
    analysis/.venv/bin/python contracts/codegen/packet_codec.py --check  # CI
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
PACKETS = ROOT / "contracts" / "packets"
SOURCE = PACKETS / "layouts.yaml"
RUST_OUT = ROOT / "core" / "src" / "packet" / "layouts.rs"

WIDTH = {"u8": 1, "u16": 2, "u32": 4, "u64": 8, "i64": 8}
#: Python struct format characters (ci/validate_contracts.py packs with these).
STRUCT_CHAR = {"u8": "B", "u16": "H", "u32": "I", "u64": "Q", "i64": "q"}


def load() -> dict:
    doc = yaml.safe_load(SOURCE.read_text())
    types = {t["pkt_t"]: t for t in doc["types"]}
    seen = set()
    for lay in doc["layouts"]:
        key = (lay["pkt_t"], lay["ver"])
        assert lay["pkt_t"] in types, f"{lay['struct']}: pkt_t {lay['pkt_t']:#04x} not in types"
        assert key not in seen, f"{lay['struct']}: (pkt_t, ver) {key} used twice"
        seen.add(key)
        for f in lay["fields"]:
            assert f["type"] in WIDTH, f"{lay['struct']}.{f['name']}: type {f['type']}"
    return doc


def offsets(lay: dict) -> list[tuple[int, dict]]:
    """(wire offset, field) for every core field; the header is 2 bytes."""
    out, at = [], 2
    for f in lay["fields"]:
        out.append((at, f))
        at += WIDTH[f["type"]]
    return out


def core_len(lay: dict) -> int:
    return sum(WIDTH[f["type"]] for f in lay["fields"])


def reserved(f: dict) -> bool:
    return f["name"].startswith("_")


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


# --- Rust ----------------------------------------------------------------------


def rust(doc: dict) -> str:
    types = {t["pkt_t"]: t for t in doc["types"]}
    vers = sorted({lay["ver"] for lay in doc["layouts"]})
    o = [
        "//! GENERATED by contracts/codegen/packet_codec.py from",
        "//! contracts/packets/layouts.yaml — do not edit; change the YAML and regenerate.",
        "",
        "use super::PacketError;",
        "",
        "/// Packet type discriminators (`pkt_t`).",
    ]
    for t in doc["types"]:
        o.append(f"pub const {t['const']}: u8 = {t['pkt_t']:#04x};")
    o.append("/// Per-type format versions (`ver`).")
    for v in vers:
        o.append(f"pub const VER_{v}: u8 = {v:#04x};")
    for lay in doc["layouts"]:
        s, n = lay["struct"], core_len(lay)
        t = types[lay["pkt_t"]]
        o += [
            "",
            f"/// {lay['doc']}",
            "///",
            f"/// `pkt_t = {lay['pkt_t']:#04x}`, `ver = {lay['ver']:#04x}`: {n}-byte core, {n + 2} on the"
            f" wire. Spec: `contracts/packets/{t['spec']}`.",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
            f"pub struct {s} {{",
        ]
        for _, f in offsets(lay):
            if reserved(f):
                continue
            o.append(f"    /// {f['doc']}")
            o.append(f"    pub {f['name']}: {f['type']},")
        o += [
            "}",
            "",
            f"impl {s} {{",
            f"    pub const PKT_T: u8 = {t['const']};",
            f"    pub const VER: u8 = VER_{lay['ver']};",
            f"    pub const CORE_LEN: usize = {n};",
            f"    pub const WIRE_LEN: usize = {n + 2};",
            "",
            "    pub fn to_bytes(&self) -> [u8; Self::WIRE_LEN] {",
            "        let mut b = [0u8; Self::WIRE_LEN];",
            "        b[0] = Self::PKT_T;",
            "        b[1] = Self::VER;",
        ]
        for at, f in offsets(lay):
            w = WIDTH[f["type"]]
            if reserved(f):
                o.append(f"        // {f['name']}: reserved, 0")
            elif w == 1:
                o.append(f"        b[{at}] = self.{f['name']};")
            else:
                o.append(f"        b[{at}..{at + w}].copy_from_slice(&self.{f['name']}.to_be_bytes());")
        o += [
            "        b",
            "    }",
            "",
            "    /// Decode from a buffer that begins with the 2-byte header; bytes",
            "    /// beyond the core are ignored.",
            "    pub fn decode(buf: &[u8]) -> Result<Self, PacketError> {",
            "        if buf.len() < 2 {",
            "            return Err(PacketError::ShortBuffer);",
            "        }",
            "        if buf[0] != Self::PKT_T || buf[1] != Self::VER {",
            "            return Err(PacketError::UnknownType(buf[0], buf[1]));",
            "        }",
            "        if buf.len() < Self::WIRE_LEN {",
            "            return Err(PacketError::ShortBuffer);",
            "        }",
            "        Ok(Self {",
        ]
        for at, f in offsets(lay):
            w, ty = WIDTH[f["type"]], f["type"]
            if reserved(f):
                continue
            if w == 1:
                o.append(f"            {f['name']}: buf[{at}],")
            else:
                o.append(f"            {f['name']}: {ty}::from_be_bytes(buf[{at}..{at + w}].try_into().unwrap()),")
        o += ["        })", "    }", "}"]
    # golden tests
    o += [
        "",
        "#[cfg(test)]",
        "mod golden {",
        "    //! Each layout against its hand-authored vectors: the decoded values",
        "    //! encode to the vector's bytes (plus any trailing padding), and the",
        "    //! bytes decode back to the values.",
        "    use super::*;",
        "",
        "    fn cases(file: &str) -> Vec<serde_json::Value> {",
        '        let path = format!("{}/../contracts/testvectors/packets/{file}", env!("CARGO_MANIFEST_DIR"));',
        "        let doc: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(&path).unwrap()).unwrap();",
        '        doc["cases"].as_array().unwrap().clone()',
        "    }",
        "",
        "    fn bytes(hex: &str) -> Vec<u8> {",
        "        (0..hex.len()).step_by(2).map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap()).collect()",
        "    }",
    ]
    for lay in doc["layouts"]:
        s = lay["struct"]
        o += [
            "",
            "    #[test]",
            f"    fn {snake(s)}_v{lay['ver']}() {{",
            f'        for case in cases("{lay["vectors"]}") {{',
            '            let (d, name) = (&case["decoded"], case["name"].as_str().unwrap());',
            f"            let p = {s} {{",
        ]
        for _, f in offsets(lay):
            if reserved(f):
                continue
            get = "as_i64" if f["type"].startswith("i") else "as_u64"
            cast = "" if f["type"] in ("u64", "i64") else f" as {f['type']}"
            o.append(f'                {f["name"]}: d["{f["name"]}"].{get}().unwrap(){cast},')
        o += [
            "            };",
            '            let want = bytes(case["hex"].as_str().unwrap());',
            "            let mut got = p.to_bytes().to_vec();",
            '            got.resize(got.len() + case["trailing_pad_bytes"].as_u64().unwrap_or(0) as usize, 0);',
            '            assert_eq!(got, want, "{name}: encode");',
            f'            assert_eq!({s}::decode(&want).unwrap(), p, "{{name}}: decode");',
            "        }",
            "    }",
        ]
    o.append("}")
    src = "\n".join(o) + "\n"
    return subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"], input=src, capture_output=True, text=True, check=True
    ).stdout


# --- Markdown -------------------------------------------------------------------


def layout_table(lay: dict) -> str:
    rows = [
        "| Offset | Width | Field | Type | Notes |",
        "|--------|-------|-------|------|-------|",
        f"| 0 | 1 | `pkt_t` | u8 | Always `{lay['pkt_t']:#04x}`. |",
        f"| 1 | 1 | `ver` | u8 | `{lay['ver']:#04x}` for this layout. |",
    ]
    for at, f in offsets(lay):
        w = WIDTH[f["type"]]
        ty = f["type"] + (" BE" if w > 1 else "")
        notes = "Reserved, `0`." if reserved(f) else f["doc"]
        rows.append(f"| {at} | {w} | `{f['name']}` | {ty} | {notes} |")
    n = core_len(lay)
    rows += ["", f"Core: {n} bytes; {n + 2} on the wire."]
    return "\n".join(rows)


def registry_table(doc: dict) -> str:
    rows = ["| `pkt_t` | Name | Layouts (`ver`: core size) | Spec |", "|---|---|---|---|"]
    for t in doc["types"]:
        lays = [x for x in doc["layouts"] if x["pkt_t"] == t["pkt_t"]]
        versions = ", ".join(f"v{x['ver']}: {core_len(x)} B (`{x['struct']}`)" for x in lays)
        rows.append(f"| `{t['pkt_t']:#04x}` | `{t['name']}` | {versions} | [`{t['spec']}`]({t['spec']}) |")
    last = max(t["pkt_t"] for t in doc["types"])
    rows += [f"| `{last + 1:#04x}` – `0x7f` | reserved | — | — |", "| `0x80` – `0xff` | private | — | — |"]
    return "\n".join(rows)


def splice(text: str, key: str, body: str, path: Path) -> str:
    begin = f"<!-- BEGIN GENERATED: {key} (contracts/packets/layouts.yaml; contracts/codegen/packet_codec.py) -->"
    end = f"<!-- END GENERATED: {key} -->"
    pat = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    if not pat.search(text):
        raise SystemExit(f"{path}: no generated block for {key}")
    return pat.sub(lambda _: f"{begin}\n{body}\n{end}", text)


def markdown(doc: dict) -> dict[Path, str]:
    types = {t["pkt_t"]: t for t in doc["types"]}
    out: dict[Path, str] = {}
    readme = PACKETS / "README.md"
    out[readme] = splice(readme.read_text(), "registry", registry_table(doc), readme)
    for lay in doc["layouts"]:
        path = PACKETS / types[lay["pkt_t"]]["spec"]
        text = out.get(path, path.read_text())
        out[path] = splice(text, f"{lay['struct']} v{lay['ver']}", layout_table(lay), path)
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    doc = load()
    outputs = {RUST_OUT: rust(doc), **markdown(doc)}
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if check:
        if stale:
            print("packet codec out of date (run contracts/codegen/packet_codec.py):")
            for p in stale:
                print("  ", p.relative_to(ROOT))
            return 1
        print("OK: packet codec and layout tables match contracts/packets/layouts.yaml.")
        return 0
    RUST_OUT.parent.mkdir(parents=True, exist_ok=True)
    for p in stale:
        p.write_text(outputs[p])
        print("wrote", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
