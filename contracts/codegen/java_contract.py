#!/usr/bin/env python3
"""Generate the Logger's wire constants (``Contract.java``) from contracts/.

Sources: versions/versions.yaml, the app-traffic parameter set's version
(app_traffic/parameters.yaml via app_params.py), enums/enums.yaml, the string enums, object
property names and REST paths of openapi/openapi.yaml, the row keys of the parquet tables the Logger
hands to the Rust core as JSON (gps, clock, radio), and
internal/mp_probe.yaml. The output is committed; ``--check`` exits 1 when it
is out of date (ci/check.sh runs that).

    analysis/.venv/bin/python contracts/codegen/java_contract.py          # write
    analysis/.venv/bin/python contracts/codegen/java_contract.py --check  # CI
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CONTRACTS = ROOT / "contracts"
OUT = ROOT / "android/logger/src/main/java/com/measurement/logger/Contract.java"

#: Parquet tables whose rows the Logger builds as JSON for the Rust core.
ROW_TABLES = {"gps": "GpsRow", "clock": "ClockRow", "radio": "RadioRow"}


def load(rel: str):
    return yaml.safe_load((CONTRACTS / rel).read_text())


def const_name(value: str) -> str:
    name = re.sub(r"[^A-Za-z0-9]+", "_", value).strip("_").upper()
    return f"_{name}" if name[:1].isdigit() else name


def class_name(key: str) -> str:
    return "".join(p.capitalize() for p in key.split("_"))


def java_value(v) -> tuple[str, str]:
    if isinstance(v, bool):
        return "boolean", "true" if v else "false"
    if isinstance(v, int):
        return "int", str(v)
    return "String", '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def strings_class(name: str, doc: str, values: list[str], indent="    ") -> list[str]:
    out = [f"{indent}/** {doc} */", f"{indent}public static final class {name} {{", f"{indent}    private {name}() {{}}", ""]
    seen = set()
    for v in values:
        c = const_name(v)
        if c in seen:
            raise SystemExit(f"{name}: two values map to {c}")
        seen.add(c)
        out.append(f'{indent}    public static final String {c} = "{v}";')
    out += [f"{indent}}}", ""]
    return out


def generate() -> str:
    lines = [
        "// GENERATED by contracts/codegen/java_contract.py from contracts/ — do not edit.",
        "// Regenerate: analysis/.venv/bin/python contracts/codegen/java_contract.py",
        "package com.measurement.logger;",
        "",
        "/** Wire constants from the single-source contracts (CLAUDE.md invariant 7). */",
        "public final class Contract {",
        "    private Contract() {}",
        "",
    ]

    # versions + pinned constants
    versions = load("versions/versions.yaml")
    lines.append("    // contracts/versions/versions.yaml")
    for section in ("versions", "auth_constants", "app_constants"):
        for k, v in (versions.get(section) or {}).items():
            t, val = java_value(v)
            lines.append(f"    public static final {t} {k.upper()} = {val};")
    lines.append("")
    # the app-traffic parameter set, written into header.json
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from app_params import params_version

    lines.append("    // contracts/app_traffic/parameters.yaml (app_params.py)")
    lines.append(f'    public static final String APP_PARAMS_VERSION = "{params_version()}";')
    lines.append("")

    # enums.yaml lists
    enums = load("enums/enums.yaml")
    yaml_sets = []
    for key, values in enums.items():
        if isinstance(values, list) and all(isinstance(v, str) for v in values):
            yaml_sets.append(set(values))
            lines += strings_class(class_name(key), f"enums.yaml {key}", values)

    # OpenAPI string enums that enums.yaml does not already hold
    openapi = load("openapi/openapi.yaml")
    for name, comp in sorted(openapi["components"]["schemas"].items()):
        values = comp.get("enum")
        if not values or set(values) in yaml_sets:
            continue
        lines += strings_class(name, f"OpenAPI {name} (a Rust enum on the server)", values)

    # property names of every OpenAPI object type (request and response bodies)
    lines += [
        "    /** Property names of the OpenAPI object types: read and write JSON bodies with these. */",
        "    public static final class Fields {",
        "        private Fields() {}",
    ]
    for name, comp in sorted(openapi["components"]["schemas"].items()):
        props = comp.get("properties")
        if not props:
            continue
        lines += ["", f"        /** OpenAPI {name} */", f"        public static final class {name} {{", f"            private {name}() {{}}", ""]
        for prop in props:
            lines.append(f'            public static final String {const_name(prop)} = "{prop}";')
        lines.append("        }")
    # JSON Schemas with no OpenAPI type (on-device files, the core's JNI results)
    for path in sorted((CONTRACTS / "schemas").glob("*.schema.json")):
        schema = json.loads(path.read_text())
        title = schema.get("title")
        props = schema.get("properties") or (schema.get("items") or {}).get("properties")
        if not title or not props or title in openapi["components"]["schemas"]:
            continue
        lines += ["", f"        /** contracts/schemas/{path.name} */", f"        public static final class {title} {{",
                  f"            private {title}() {{}}", ""]
        for prop in props:
            lines.append(f'            public static final String {const_name(prop)} = "{prop}";')
        lines.append("        }")
    lines += ["    }", ""]

    # REST paths
    lines += [
        "    /** REST paths (OpenAPI operationId); fill {params} in order with {@link #path}. */",
        "    public static final class Api {",
        "        private Api() {}",
        "",
    ]
    for path, ops in sorted(openapi["paths"].items()):
        for method, op in ops.items():
            if isinstance(op, dict) and op.get("operationId"):
                lines.append(f"        /** {method.upper()} */")
                lines.append(f'        public static final String {const_name(op["operationId"])} = "{path}";')
    lines += [
        "",
        "        /** The template with each {param} replaced by the next argument. */",
        "        public static String path(String template, Object... args) {",
        "            StringBuilder sb = new StringBuilder();",
        "            int i = 0;",
        "            int a = 0;",
        "            while (i < template.length()) {",
        "                int open = template.indexOf('{', i);",
        "                if (open < 0) {",
        "                    sb.append(template, i, template.length());",
        "                    break;",
        "                }",
        "                int close = template.indexOf('}', open);",
        "                if (a >= args.length) {",
        '                    throw new IllegalArgumentException("missing value for " + template.substring(open, close + 1));',
        "                }",
        "                sb.append(template, i, open).append(args[a++]);",
        "                i = close + 1;",
        "            }",
        "            if (a != args.length) {",
        '                throw new IllegalArgumentException("too many values for " + template);',
        "            }",
        "            return sb.toString();",
        "        }",
        "    }",
        "",
    ]

    # row keys for the JSON the Logger passes to the Rust core
    for table, cls in ROW_TABLES.items():
        spec = load(f"parquet/{table}.parquet.yaml")
        lines += [
            f"    /** Keys of a {table} row passed to RustCore (contracts/parquet/{table}.parquet.yaml). */",
            f"    public static final class {cls} {{",
            f"        private {cls}() {{}}",
            "",
        ]
        nested = []
        for col in spec["columns"]:
            lines.append(f'        public static final String {const_name(col["name"])} = "{col["name"]}";')
            item = col.get("item") or {}
            if item.get("type") == "struct":
                nested.append((class_name(col["name"]), col["name"], item["fields"]))
        for name, col, fields in nested:
            lines += ["", f"        /** Keys of one {col} item. */", f"        public static final class {name} {{",
                      f"            private {name}() {{}}", ""]
            for f in fields:
                lines.append(f'            public static final String {const_name(f["name"])} = "{f["name"]}";')
            lines.append("        }")
        lines += ["    }", ""]

    # mp-probe
    probe = load("internal/mp_probe.yaml")
    lines += [
        "    /** mp-probe control protocol and records (contracts/internal/mp_probe.yaml). */",
        "    public static final class MpProbe {",
        "        private MpProbe() {}",
        "",
        f"        public static final int PORT = {probe['port']};",
        f"        public static final int FAST_MAX_S = {probe['fast_max_s']};",
        f'        public static final String TEST_FILE = "{probe['test_file']}";',
    ]
    for cmd in probe["commands"]:
        lines.append(f'        public static final String {cmd["name"]} = "{cmd["name"]}";')
    for cmd in probe["commands"]:
        word = cmd["reply"].split()[0]
        if not word.startswith("<"):
            lines.append(f'        public static final String REPLY_{cmd["name"]} = "{word}";')
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def main() -> int:
    text = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"ERROR: {OUT.relative_to(ROOT)} is out of date with contracts/. Run:")
            print("  analysis/.venv/bin/python contracts/codegen/java_contract.py")
            return 1
        print("OK: generated Java contract constants match contracts/.")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
